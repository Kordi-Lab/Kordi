#!/usr/bin/env node
/* Writes every artifact derived from birds.mjs. Run with --check to fail when an
 * output on disk differs from what the generator would write. */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { BG_PLACEHOLDER, SPECIES, TONES, birdSvg, seedToAvatar } from './birds.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');
const previewScript = join(root, 'docs/design-previews/agent-bird-avatars/birds.js');
const serverDir = join(root, 'bridges/cloud-server/src/avatars/birds');
const templateDir = join(serverDir, 'templates');
const templatesRs = join(serverDir, 'templates.rs');
const fixturesJson = join(here, 'fixtures.json');

/* Shared with the desktop and iOS clients; every platform must agree. */
export const FIXTURES = {
  'bird-osprey-color-sky': ['osprey', 'color', 'sky'],
  'bird-owl-ink-paper': ['owl', 'ink', 'paper'],
  'bird-jay-mint': ['jay', 'color', 'mint'],
  'cloud-local-agent': ['sparrow', 'color', 'mint'],
  'default-agent-acct_123': ['eagle', 'color', 'coral'],
  agent_definition_avatar: ['cardinal', 'color', 'butter'],
  '3f9a1c2e4b5d6f70': ['cockatoo', 'color', 'butter'],
  '7bbaa257': ['penguin', 'color', 'mint'],
  cloud_agent_kordi_pip: ['owl', 'color', 'sakura'],
  a: ['toucan', 'color', 'rice'],
  '': ['hummingbird', 'color', 'mint'],
  'bird-dragon-color-sky': ['sparrow', 'color', 'sakura'],
};

export function templateSvg(species, tone) {
  return `${birdSvg(species, { tone, palette: BG_PLACEHOLDER, size: 128, radius: 0, idPrefix: 'kb' })}\n`;
}

function browserScript() {
  const source = readFileSync(join(here, 'birds.mjs'), 'utf8');
  const body = source
    .replace(/^\/\*[\s\S]*?\*\/\n\n/, '')
    .replace(/^import .*\n/gm, '')
    .replace(/^export /gm, '')
    .trimEnd()
    .split('\n')
    .map((line) => (line ? `  ${line}` : line))
    .join('\n');
  return [
    '/* Generated by scripts/kordi-birds/generate.mjs from scripts/kordi-birds/birds.mjs. Do not edit.',
    ' * Kordi agent bird avatars for the browser preview; sets window.KordiBirds. */',
    '(function () {',
    "  'use strict';",
    '',
    body,
    '',
    '  window.KordiBirds = { SPECIES, PALETTES, TONES, birdSvg, seedToAvatar, tintForSpecies, hash, BG_PLACEHOLDER };',
    '})();',
    '',
  ].join('\n');
}

function templatesModule(pairs) {
  return [
    '// Generated by scripts/kordi-birds/generate.mjs. Do not edit.',
    '',
    '/// (species, tone, SVG template with a `__BG__` background placeholder).',
    'pub(super) const TEMPLATES: &[(&str, &str, &str)] = &[',
    ...pairs.map(([species, tone]) => {
      const fields = [`"${species}"`, `"${tone}"`, `include_str!("templates/${species}-${tone}.svg")`];
      const inline = `(${fields.join(', ')})`;
      // Match rustfmt: tuple fields up to 60 columns (fn_call_width) stay on one line.
      return inline.length - 2 <= 60
        ? `    ${inline},`
        : `    (\n${fields.map((field) => `        ${field},`).join('\n')}\n    ),`;
    }),
    '];',
    '',
  ].join('\n');
}

function fixtures() {
  const out = {};
  for (const [seed, [species, tone, palette]] of Object.entries(FIXTURES)) {
    const actual = seedToAvatar(seed);
    if (actual.species !== species || actual.tone !== tone || actual.palette !== palette) {
      throw new Error(`fixture ${JSON.stringify(seed)} maps to ${JSON.stringify(actual)}`);
    }
    out[seed] = { species, tone, palette };
  }
  return `${JSON.stringify(out, null, 2)}\n`;
}

export function outputs() {
  const pairs = SPECIES.flatMap(({ key }) => TONES.map((tone) => [key, tone]));
  const files = new Map();
  files.set(previewScript, browserScript());
  for (const [species, tone] of pairs) {
    files.set(join(templateDir, `${species}-${tone}.svg`), templateSvg(species, tone));
  }
  files.set(templatesRs, templatesModule(pairs));
  files.set(fixturesJson, fixtures());
  return files;
}

function main() {
  const check = process.argv.includes('--check');
  const files = outputs();
  const stale = [];
  for (const [path, content] of files) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (current === content) continue;
    if (check) {
      stale.push(relative(root, path));
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
    }
  }
  if (existsSync(templateDir)) {
    for (const name of readdirSync(templateDir)) {
      if (!files.has(join(templateDir, name))) stale.push(`${relative(root, join(templateDir, name))} (unexpected)`);
    }
  }
  if (stale.length) {
    console.error(`kordi-birds outputs are out of date; run node scripts/kordi-birds/generate.mjs\n  ${stale.join('\n  ')}`);
    process.exit(1);
  }
  if (!check) console.log(`kordi-birds: ${files.size} outputs up to date`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
